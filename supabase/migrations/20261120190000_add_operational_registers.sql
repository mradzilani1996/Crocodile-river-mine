-- Operational registers: shift handover, stock reconciliation and magazine access.
create table if not exists public.ems_shift_handovers (
  id uuid primary key default gen_random_uuid(),
  handover_number bigint generated by default as identity unique,
  handover_date date not null default current_date,
  shift text not null check (shift in ('day','night')),
  outgoing_person text not null,
  incoming_person text not null,
  stock_status text not null default 'checked' check (stock_status in ('checked','discrepancy','not_checked')),
  security_status text not null default 'satisfactory' check (security_status in ('satisfactory','issue_reported','not_checked')),
  seal_key_status text not null default 'intact' check (seal_key_status in ('intact','exception_recorded','not_checked')),
  outstanding_matters text,
  handover_notes text,
  handed_over_by uuid not null references auth.users(id),
  handed_over_by_name text not null,
  received_by uuid references auth.users(id),
  received_by_name text,
  acknowledged_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.ems_stocktakes (
  id uuid primary key default gen_random_uuid(),
  stocktake_number bigint generated by default as identity unique,
  count_date date not null default current_date,
  product_id uuid not null references public.ems_explosive_products(id),
  system_balance numeric(14,3) not null,
  physical_balance numeric(14,3) not null,
  variance numeric(14,3) generated always as (physical_balance - system_balance) stored,
  discrepancy_notes text,
  counted_by uuid not null references auth.users(id),
  counted_by_name text not null,
  status text not null default 'pending_verification' check (status in ('pending_verification','verified','adjustment_required')),
  verified_by uuid references auth.users(id),
  verified_by_name text,
  verified_at timestamptz,
  verification_notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.ems_magazine_access_log (
  id uuid primary key default gen_random_uuid(),
  access_number bigint generated by default as identity unique,
  access_time timestamptz not null default now(),
  person_name text not null,
  company_number text,
  employer text,
  access_type text not null check (access_type in ('entry','exit')),
  purpose text not null,
  authorised_by text,
  logged_by uuid not null references auth.users(id),
  logged_by_name text not null,
  comments text,
  created_at timestamptz not null default now()
);
alter table public.ems_shift_handovers enable row level security;
alter table public.ems_stocktakes enable row level security;
alter table public.ems_magazine_access_log enable row level security;
create policy "Active EMS users view shift handovers" on public.ems_shift_handovers for select to authenticated using (app_private.is_active_user());
create policy "Magazine team records shift handovers" on public.ems_shift_handovers for insert to authenticated with check (app_private.is_active_user() and handed_over_by = auth.uid() and app_private.current_role() in ('admin'::ems_user_role,'magazine_master'::ems_user_role,'issuer'::ems_user_role));
create policy "Active EMS users view stocktakes" on public.ems_stocktakes for select to authenticated using (app_private.is_active_user());
create policy "Magazine team records stocktakes" on public.ems_stocktakes for insert to authenticated with check (app_private.is_active_user() and counted_by = auth.uid() and app_private.current_role() in ('admin'::ems_user_role,'magazine_master'::ems_user_role));
create policy "Management verifies stocktakes" on public.ems_stocktakes for update to authenticated using (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role)) with check (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role));
create policy "Active EMS users view magazine access log" on public.ems_magazine_access_log for select to authenticated using (app_private.is_active_user());
create policy "Magazine team logs magazine access" on public.ems_magazine_access_log for insert to authenticated with check (app_private.is_active_user() and logged_by = auth.uid() and app_private.current_role() in ('admin'::ems_user_role,'magazine_master'::ems_user_role,'issuer'::ems_user_role));
create index if not exists ems_shift_handovers_date_idx on public.ems_shift_handovers(handover_date desc);
create index if not exists ems_stocktakes_date_idx on public.ems_stocktakes(count_date desc);
create index if not exists ems_magazine_access_time_idx on public.ems_magazine_access_log(access_time desc);