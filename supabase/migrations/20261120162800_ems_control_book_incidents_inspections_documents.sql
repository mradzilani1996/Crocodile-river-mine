-- Crocodile River Mine EMS capability expansion
-- Based on MIN-DOC-0052 Explosives Control Book (uploaded Rev 5 reference).
-- Apply this migration to the Crocodile River Mine EMS Supabase project.

alter table public.ems_stock_transactions
  add column if not exists control_book_section text
    check (control_book_section in ('Boxes','Bags','Tamping')),
  add column if not exists container_number text,
  add column if not exists item_type text,
  add column if not exists item_description text,
  add column if not exists package_quantity numeric(14,3) not null default 0 check (package_quantity >= 0),
  add column if not exists unit_quantity numeric(14,3) not null default 0 check (unit_quantity >= 0),
  add column if not exists work_section text,
  add column if not exists miner_company_number text,
  add column if not exists miner_name text,
  add column if not exists miner_acknowledged boolean not null default false;

create index if not exists ems_stock_transactions_book_idx
  on public.ems_stock_transactions(control_book_section, container_number, transaction_date);

create table if not exists public.ems_incidents (
  id uuid primary key default gen_random_uuid(),
  incident_number bigint generated by default as identity unique,
  incident_date timestamptz not null default now(),
  incident_type text not null check (incident_type in ('shortage','over-issue','unreturned-stock','damaged-packaging','documentation-error','security-concern','other')),
  severity text not null default 'low' check (severity in ('low','medium','high','critical')),
  location text not null,
  description text not null,
  immediate_action text,
  reported_by uuid not null references auth.users(id),
  reporter_name text not null,
  status text not null default 'open' check (status in ('open','under_review','action_required','closed')),
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  review_notes text,
  corrective_action text,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ems_inspections (
  id uuid primary key default gen_random_uuid(),
  inspection_number bigint generated by default as identity unique,
  inspection_date date not null default current_date,
  inspection_type text not null,
  location text not null,
  inspector_id uuid not null references auth.users(id),
  inspector_name text not null,
  findings text not null,
  non_conformances text,
  corrective_actions text,
  responsible_person text,
  due_date date,
  status text not null default 'open' check (status in ('open','in_progress','verified','closed')),
  verified_by uuid references auth.users(id),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ems_document_register (
  id uuid primary key default gen_random_uuid(),
  document_number text not null unique,
  title text not null,
  document_type text not null,
  revision text not null,
  effective_date date,
  review_date date,
  storage_path text,
  external_url text,
  status text not null default 'current' check (status in ('draft','current','superseded','withdrawn')),
  uploaded_by uuid references auth.users(id),
  uploaded_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (storage_path is not null or external_url is not null)
);

alter table public.ems_incidents enable row level security;
alter table public.ems_inspections enable row level security;
alter table public.ems_document_register enable row level security;

create policy "Active users view EMS incidents" on public.ems_incidents
for select to authenticated using (app_private.is_active_user());
create policy "Active users report EMS incidents" on public.ems_incidents
for insert to authenticated with check (app_private.is_active_user() and reported_by = auth.uid());
create policy "Management reviews EMS incidents" on public.ems_incidents
for update to authenticated
using (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role))
with check (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role));

create policy "Active users view EMS inspections" on public.ems_inspections
for select to authenticated using (app_private.is_active_user());
create policy "Authorised users create EMS inspections" on public.ems_inspections
for insert to authenticated with check (
  app_private.is_active_user() and inspector_id = auth.uid()
  and app_private.current_role() in ('admin'::ems_user_role,'magazine_master'::ems_user_role,'authorising_officer'::ems_user_role,'management'::ems_user_role)
);
create policy "Management updates EMS inspections" on public.ems_inspections
for update to authenticated
using (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role))
with check (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role));

create policy "Active users view EMS document register" on public.ems_document_register
for select to authenticated using (app_private.is_active_user());
create policy "Admins manage EMS document register" on public.ems_document_register
for all to authenticated
using (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role))
with check (app_private.is_active_user() and app_private.current_role() in ('admin'::ems_user_role,'management'::ems_user_role));
